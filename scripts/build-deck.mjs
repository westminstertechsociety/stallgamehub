// Builds decks/human-or-ai.json for the Human or AI game. Runs at build time with internet; the fair ships
// the static deck. Re-runnable: every stage caches under .deckwork/ (gitignored, never committed).
//
//   node scripts/build-deck.mjs                 run every stage that has no cache yet
//   node scripts/build-deck.mjs --humans        (re)select the human half from the Enron corpus
//   node scripts/build-deck.mjs --generate      (re)generate AI counterparts via OpenRouter
//   node scripts/build-deck.mjs --calibrate     (re)estimate difficulty with cheap judge models
//   node scripts/build-deck.mjs --tells         (re)draft tells with a small Claude model for hand editing
//   node scripts/build-deck.mjs --assemble      write the deck from the caches
//
// Human half: the CMU Enron corpus (1999-2002, provably pre-LLM). Only folders of mail the person sent
// themselves are used, bodies only, anonymised, era-neutral, sensitive topics skipped rather than redacted.
// AI half: one counterpart per human item matched on purpose, length, register and formatting, generated by a
// rotation of cheap models at varied temperature so no single voice gives the game away.

