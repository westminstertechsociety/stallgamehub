function ensureCorpus() {
  if (existsSync(MAILDIR) && readdirSync(MAILDIR).length > 0) return
  if (!existsSync(ARCHIVE)) {
    log(`downloading ${ARCHIVE_URL} (about 420 MB)`)
    const r = spawnSync('curl', ['-L', '--progress-bar', '-o', ARCHIVE, ARCHIVE_URL], { stdio: 'inherit' })
    if (r.status !== 0) throw new Error('download failed')
  }
  log('extracting sent folders only (this takes a few minutes)')
  mkdirSync(work, { recursive: true })
  const r = spawnSync(
    'tar',
    ['-xzf', ARCHIVE, '-C', work, '--wildcards', '*/sent/*', '*/sent_items/*', '*/_sent_mail/*'],
    { stdio: 'inherit' },
  )
  if (r.status !== 0) throw new Error('extract failed')
}

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name)
    const st = statSync(p)
    if (st.isDirectory()) yield* walk(p)
    else yield p
  }
}

