// First and last names seen in the corpus headers; built while scanning.
const NAME_TOKENS = new Set()
function harvestNames(headers) {
  for (const line of headers.match(/^X-(?:From|To|cc|bcc):.*$/gim) ?? []) {
    for (const tok of line.replace(/^X-[A-Za-z]+:/, '').replace(/<[^>]*>|@\S+|\/[A-Z=\w]+/g, ' ').split(/[\s,;"'()]+/)) {
      const t = tok.toLowerCase().replace(/[^a-z-]/g, '')
      if (t.length >= 3 && !NAME_ALLOW.has(t)) NAME_TOKENS.add(t)
    }
  }
}

function parseMessage(raw) {
  const split = raw.indexOf('\n\n')
  if (split < 0) return null
  const headers = raw.slice(0, split)
  let body = raw.slice(split + 2)
  harvestNames(headers)
  const from = /^X-From:\s*(.*)$/im.exec(headers)?.[1] ?? ''
  const subject = /^Subject:\s*(.*)$/im.exec(headers)?.[1] ?? ''
  // Cut at the first quoted or forwarded block; keep what the author typed.
  let cut = body.length
  for (const re of QUOTE_MARKERS) {
    const m = re.exec(body)
    if (m && m.index < cut) cut = m.index
  }
  body = body.slice(0, cut)
  // Quoted-printable leftovers and hard wraps.
  body = body.replace(/=20/g, ' ').replace(/=09/g, ' ').replace(/=\r?\n/g, '').replace(/\r/g, '')
  body = body.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim()
  // Drop a trailing sign-off and the name lines after it.
  const lines = body.split('\n')
  while (lines.length) {
    const last = lines[lines.length - 1].trim()
    if (
      !last ||
      SIGNOFF.test(last.replace(/,$/, '')) ||
      /^[A-Z][a-z]+( [A-Z]\.?)?( [A-Z][a-z]+)?$/.test(last) ||
      /^[A-Za-z]{1,4}[.]?$/.test(last) ||
      /^-+$/.test(last)
    )
      lines.pop()
    else break
  }
  body = lines.join('\n').trim()
  return { from, subject, body }
}

function anonymise(text, authorFirst) {
  const map = new Map()
  let next = 0
  const sub = (name) => {
    const key = name.toLowerCase()
    if (!map.has(key)) map.set(key, NEUTRAL[next++ % NEUTRAL.length])
    return map.get(key)
  }
  // "Firstname Lastname" pairs and lone first names from the list; the author's own name too.
  let out = text.replace(/\b([A-Z][a-z]{2,})\s+([A-Z][a-z]+(?:-[A-Z][a-z]+)?)\b/g, (m, a, _b) => (FIRST_NAMES.has(a.toLowerCase()) ? sub(a) : m))
  out = out.replace(/\b([A-Z][a-z]{2,})\b/g, (m, a) => (FIRST_NAMES.has(a.toLowerCase()) ? sub(a) : m))
  if (authorFirst && authorFirst.length > 2) out = out.replace(new RegExp(`\\b${authorFirst}\\b`, 'gi'), sub(authorFirst))
  // Anything still looking like a surname after a substituted name is a leak: "Alex Lavorato".
  if (/\b(?:Alex|Sam|Jordan|Taylor|Morgan|Casey|Riley|Jamie|Drew|Robin|Avery|Quinn) [A-Z][a-z]+\b/.test(out)) return null
  return out
}

function registerOf(text) {
  const w = words(text)
  const lower = text === text.toLowerCase()
  const greeting = /^(hi|hello|hey|dear|good morning|good afternoon)\b/i.test(text)
  const exclaim = (text.match(/!/g) ?? []).length
  const question = /\?/.test(text)
  const typos = /\b(teh|recieve|seperate|definately|alot|thier|occured|untill)\b/i.test(text) || /\s[,.]/.test(text)
  const caps = w.filter((x) => /^[A-Z]{2,}$/.test(x)).length
  return { words: w.length, lower, greeting, exclaim, question, typos, caps, lines: text.split('\n').length }
}

function bodyOk(text, subject) {
  const n = words(text).length
  if (n < 15 || n > 60) return 'length'
  if (FORMAT_SKIP.test(text) || FORMAT_SKIP.test(subject)) return 'format'
  if (SKIP_SYMBOLS.test(text) || MONTHS.test(text)) return 'numbers'
  if (SKIP_WORDS.test(text) || SKIP_WORDS.test(subject)) return 'topic'
  if (SKIP_TONE.test(text) || SKIP_TONE.test(subject)) return 'tone'
  // Acronyms are organisations, systems or jargon nine times out of ten.
  const acronyms = (text.match(/\b[A-Z]{2,}\b/g) ?? []).filter((a) => !new Set(['OK', 'PS', 'FYI', 'ASAP', 'AM', 'PM', 'TV', 'PC', 'US', 'UK', 'IT', 'HR', 'CEO', 'BTW', 'RSVP', 'ID']).has(a))
  if (acronyms.length) return 'acronym'
  if (text.split('\n').filter((l) => l.trim() && words(l).length < 4).length > 2) return 'mangled'
  if (/^\s*\d+[.)]/m.test(text)) return 'list'
  const dict = dictionary()
  let unknown = 0
  for (const raw of text.split(/[^A-Za-z'-]+/)) {
    const t = raw.toLowerCase().replace(/^'+|'+$/g, '')
    if (t.length < 3) continue
    if (NAME_TOKENS.has(t) && !NAME_ALLOW.has(t) && !dict.has(t)) return `name:${t}`
    if (!dict.has(t) && !dict.has(t.replace(/'s$/, '')) && !/^(?:\w)\1*$/.test(t)) {
      if (NAME_TOKENS.has(t)) return `name:${t}`
      unknown++
      if (unknown > 1) return `unknown:${t}`
    }
  }
  return null
}

function selectHumans() {
  const cache = path.join(work, 'humans.json')
  ensureCorpus()
  // Pass one: parse everything (harvesting names from headers) and keep bodies that look promising.
  const parsed = []
  let scanned = 0
  for (const file of walk(MAILDIR)) {
    scanned++
    let raw
    try {
      raw = readFileSync(file, 'latin1')
    } catch {
      continue
    }
    const msg = parseMessage(raw)
    if (!msg || !msg.body) continue
    const n = words(msg.body).length
    if (n < 15 || n > 60) continue
    parsed.push(msg)
  }
  log(`scanned ${scanned} messages, ${parsed.length} bodies of 15-60 words, ${NAME_TOKENS.size} name tokens harvested`)
  // Pass two: strict filters now that the name list is complete.
  const seen = new Set()
  const candidates = []
  const reasons = {}
  for (const msg of parsed) {
    const why = bodyOk(msg.body, msg.subject)
    if (why) {
      const k = why.split(':')[0]
      reasons[k] = (reasons[k] ?? 0) + 1
      continue
    }
    const authorFirst = (msg.from.match(/,\s*([A-Za-z]+)/)?.[1] ?? msg.from.split(/\s+/)[0] ?? '').replace(/[^A-Za-z]/g, '')
    const text = anonymise(msg.body, authorFirst)
    if (!text) continue
    // Any remaining capitalised word that is neither a sentence start, a weekday, nor a neutral name: skip.
    const suspects = text.match(/(?<![.!?\n]\s|^)\b[A-Z][a-z]{2,}\b/g) ?? []
    const allowed = new Set([...NEUTRAL, 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday', 'Thanks', 'Please', 'Also', 'Just', 'Let', 'The', 'This', 'That', 'Yes', 'Okay', 'Sorry', 'Great', 'Good', 'Thank', 'Hope', 'Would', 'Could', 'Can', 'Will', 'Should', 'What', 'When', 'Where', 'Who', 'How', 'Why', 'Any', 'All', 'One', 'Two', 'Three', 'Since', 'After', 'Before', 'Then', 'Here', 'There', 'Not', 'Are', 'Was', 'Were', 'Have', 'Has', 'Had', 'And', 'But', 'For', 'With', 'From', 'Your', 'You', 'Our', 'Its', 'His', 'Her', 'Him', 'She', 'They', 'Them', 'Their', 'Some', 'Each', 'Every', 'Most', 'Much', 'Many', 'Very', 'Well', 'Still', 'Sure', 'Maybe', 'Perhaps', 'Probably', 'Anyway', 'Again', 'Unfortunately', 'Hopefully', 'Actually', 'Basically', 'Apparently', 'Obviously', 'Finally', 'First', 'Second', 'Last', 'Next', 'Today', 'Tomorrow', 'Yesterday', 'Tonight', 'Morning', 'Afternoon', 'Evening', 'Week', 'Month', 'Year', 'Meeting', 'Call', 'Note', 'Fyi', 'Hi', 'Hello', 'Hey', 'Dear', 'Cheers', 'Regards', 'Best', 'Ok', 'Yeah', 'Also', 'However', 'Otherwise', 'Thursday'])
    if (suspects.some((w) => !allowed.has(w))) {
      reasons.capitalised = (reasons.capitalised ?? 0) + 1
      continue
    }
    const key = text.toLowerCase().replace(/[^a-z]/g, '').slice(0, 80)
    if (seen.has(key)) continue
    seen.add(key)
    candidates.push({ text, reg: registerOf(text), subject: msg.subject })
  }
  log(`${candidates.length} clean candidates; rejected: ${Object.entries(reasons).map(([k, v]) => `${k} ${v}`).join(', ')}`)
  // Spread across lengths and registers, deterministic per run.
  const rand = mulberry32(20260916)
  const buckets = { short: [], mid: [], long: [] }
  for (const c of candidates) (c.reg.words <= 25 ? buckets.short : c.reg.words <= 40 ? buckets.mid : buckets.long).push(c)
  const pick = []
  const per = Math.ceil(TARGET_HUMANS / 3)
  for (const b of Object.values(buckets)) {
    const shuffled = shuffle(b, rand)
    const groups = [
      shuffled.filter((c) => c.reg.lower),
      shuffled.filter((c) => c.reg.question),
      shuffled.filter((c) => c.reg.greeting),
      shuffled.filter((c) => !c.reg.greeting && !c.reg.lower),
    ]
    const chosen = new Set()
    let gi = 0
    while (chosen.size < per && groups.some((g) => g.length)) {
      const g = groups[gi % groups.length]
      gi++
      const c = g.shift()
      if (c && !chosen.has(c)) chosen.add(c)
    }
    pick.push(...chosen)
  }
  const humans = pick.slice(0, TARGET_HUMANS).map((c) => ({
    id: `h-${sha(c.text)}`,
    text: c.text,
    source: 'human',
    register: c.reg,
  }))
  writeJson(cache, humans)
  log(`selected ${humans.length} human items -> ${cache}`)
  return humans
}

function mulberry32(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
function shuffle(items, rand) {
  const out = [...items]
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[out[i], out[j]] = [out[j], out[i]]
  }
  return out
}

