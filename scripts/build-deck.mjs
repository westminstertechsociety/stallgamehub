const humansCache = path.join(work, 'humans.json')
let humans = readJson(humansCache, null)
if (want('--humans') && (explicit || !humans)) humans = selectHumans()
if (!humans) throw new Error('no humans selected; run with --humans')

let ai = readJson(path.join(work, 'ai.json'), {})
if (want('--generate') && (explicit || Object.keys(ai).length < humans.length)) ai = await generateAi(humans)

const paired = humans.filter((h) => ai[h.id])
const all = [...paired, ...paired.map((h) => ai[h.id])]
let votes = readJson(path.join(work, 'votes.json'), {})
if (want('--calibrate') && (explicit || Object.keys(votes).length < paired.length)) votes = await calibrate(paired, ai)

let tells = readJson(path.join(work, 'tells.json'), {})
if (want('--tells') && (explicit || Object.keys(tells).length < all.length)) tells = await draftTells(all)

if (want('--assemble')) assemble(paired, ai, votes, tells)
